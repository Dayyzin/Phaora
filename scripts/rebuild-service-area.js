#!/usr/bin/env node
/**
 * Relink the service-area page to every town page on disk.
 *
 * There are 104 town pages and this page listed 20 of them. Andover — 9,026
 * households — had no inbound link from anywhere on the site, which for a
 * crawler means it does not exist. A page nothing links to does not rank, and
 * the forty-eight pages just written were all in that position or close to it.
 *
 * COUNTY IS READ, NOT RECALLED. Each tile prints a county, and a wrong one is a
 * published error. Counties come from two places, in order: the sentence the
 * town page already carries ('Brookline is Norfolk County, Massachusetts' —
 * itself sourced from the Census when that page was generated), and the tiles
 * already on this page. A town that resolves from neither is listed without a
 * county rather than with a guessed one, and the script says which.
 *
 * Rewrites only the block between the town-grid markers. Everything else in the
 * file — header, copy, styles, footer — is left exactly as found.
 */
const fs = require('fs')
const path = require('path')

const ROOT = path.join(__dirname, '..')
const FILE = path.join(ROOT, 'service-area', 'index.html')

const STATE_NAME = {
  ma: 'Massachusetts', ri: 'Rhode Island', ct: 'Connecticut',
  nh: 'New Hampshire', me: 'Maine',
}
/** The order the grid reads in. Home state first, then out. */
const STATE_ORDER = ['ma', 'ri', 'nh', 'me', 'ct']

function titleFromSlug(slug) {
  return slug.split('-').map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join(' ')
}

function main() {
  const html = fs.readFileSync(FILE, 'utf8')

  // Counties already printed on this page, so nothing regresses.
  const known = new Map()
  for (const m of html.matchAll(
    /<a href="\/masonry-([a-z-]+)-(ma|ri|nh|me|ct)\/"><b>([^<]+)<\/b><span>([^<]*)<\/span><\/a>/g,
  )) {
    known.set(`${m[1]}-${m[2]}`, { name: m[3], county: m[4] })
  }

  const dirs = fs
    .readdirSync(ROOT)
    .filter((d) => /^masonry-[a-z-]+-(ma|ri|nh|me|ct)$/.test(d))
    .filter((d) => fs.existsSync(path.join(ROOT, d, 'index.html')))
    .sort()

  const towns = []
  const noCounty = []

  for (const dir of dirs) {
    const key = dir.replace(/^masonry-/, '')
    const m = /^(.+)-(ma|ri|nh|me|ct)$/.exec(key)
    const slug = m[1]
    const state = m[2]
    const page = fs.readFileSync(path.join(ROOT, dir, 'index.html'), 'utf8')

    // The page's own <title> carries the display name, which is the one place
    // that already handles Manchester-by-the-Sea and the rest.
    const t = /<title>[^<]*?in ([^,<]+),/.exec(page)
    const prior = known.get(key)
    const name = (t && t[1].trim()) || (prior && prior.name) || titleFromSlug(slug)

    // 'X is Norfolk County, Massachusetts' / 'X sits in Middlesex County, ...'
    const c = /\b(?:is|sits in|is in)\s+([A-Z][A-Za-z ]*?)\s+County\b/.exec(page)
    // Connecticut abolished county government in 2022 and the pages there name
    // a planning region instead — correctly, which is why the County pattern
    // finds nothing and must not be forced to.
    const r = /\bthe\s+([A-Z][A-Za-z ]*?)\s+planning region\b/.exec(page)
    const county = (c && c[1].trim()) || (r && r[1].trim()) || (prior && prior.county) || null
    if (!county) noCounty.push(`${name}, ${state.toUpperCase()}`)

    towns.push({ key, slug, state, name, county })
  }

  const sections = STATE_ORDER.filter((st) => towns.some((t) => t.state === st)).map((st) => {
    const rows = towns
      .filter((t) => t.state === st)
      .sort((a, b) => a.name.localeCompare(b.name))
      .map(
        (t) =>
          `      <a href="/masonry-${t.slug}-${t.state}/"><b>${t.name}</b><span>${t.county ?? ''}</span></a>`,
      )
      .join('\n')
    return (
      `    <h3 class="tp-h3">${STATE_NAME[st]}</h3>\n` +
      `    <div class="tp-towns">\n${rows}\n    </div>`
    )
  })

  const block =
    `    <!-- TOWN GRID: generated by scripts/rebuild-service-area.js -->\n` +
    sections.join('\n') +
    `\n    <!-- /TOWN GRID -->`

  // Replace from the first town grid through the last, leaving the section
  // heading and everything around it alone.
  const start = html.indexOf('      <a href="/masonry-')
  if (start === -1) { console.error('no town grid found — refusing to guess where it goes'); process.exit(1) }
  const gridOpen = html.lastIndexOf('<div class="tp-towns">', start)
  const lastLink = html.lastIndexOf('<a href="/masonry-')
  const gridClose = html.indexOf('</div>', lastLink)
  if (gridOpen === -1 || gridClose === -1) { console.error('could not bound the grid'); process.exit(1) }

  const out = html.slice(0, gridOpen) + block.trimStart() + html.slice(gridClose + '</div>'.length)
  fs.writeFileSync(FILE, out)

  console.log(`service-area/index.html — ${towns.length} towns across ${sections.length} states`)
  for (const st of STATE_ORDER) {
    const n = towns.filter((t) => t.state === st).length
    if (n) console.log(`  ${STATE_NAME[st]}: ${n}`)
  }
  if (noCounty.length) {
    console.log(`  ${noCounty.length} listed without a county (not guessed):`)
    for (const n of noCounty) console.log(`    ${n}`)
  }
}

main()

#!/usr/bin/env node
/**
 * Write the town entries the site has no page for.
 *
 * The bench holds 96 towns of households; the site has 56 town pages. The gap
 * is not random — the pages were built for the shore, and the bench has since
 * taken on the inland money. Brookline is 5,897 households at an average
 * assessed value of $2.86m and there is nowhere for that search to land.
 *
 * EVERY FACT HERE IS SOURCED, NONE IS RECALLED. County comes from the Census
 * geocoder, asked what county a real parcel in that town sits in. Distances are
 * measured between parcel-median centroids. Nothing in the generated prose says
 * anything this file did not read from one of those two places — no founding
 * date, no price, no square footage, no credential, no claim about who we are.
 *
 * Input is /tmp/town-gap.json, written by admin-phaora's tmp-towngap.mts.
 * Output is scripts/town-gap-data.js, which generate-town-pages.js concatenates
 * onto its hand-written list. The 56 existing entries are never touched.
 */
const fs = require('fs')
const path = require('path')

const ROOT = path.join(__dirname, '..')
const IN = process.argv[2] || '/tmp/town-gap.json'
const OUT = path.join(__dirname, 'town-gap-data.js')

const STATE_NAME = {
  ma: 'Massachusetts', ri: 'Rhode Island', ct: 'Connecticut',
  nh: 'New Hampshire', me: 'Maine',
}

function slugify(name) {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
}

/**
 * Sentences built only from county, state and measured distance.
 *
 * Four forms rather than one: forty-eight pages carrying an identical sentence
 * with the nouns swapped is duplicate content, and Google reads it as exactly
 * that. Rotated by index so adjacent towns — which is to say towns whose pages
 * link to each other — never share a shape.
 */
const FORMS = [
  (t, n, s) =>
    `${t.name} is ${t.county} County, ${s}. ${list(n)} are all within ${Math.max(...n.map((x) => x.miles))} miles of it, and one run covers the lot.`,
  (t, n, s) =>
    `${t.name} sits in ${t.county} County, ${s}, with ${n[0].town} ${n[0].miles} miles out and ${n[1].town} ${n[1].miles} — close enough that the same crew takes all three.`,
  (t, n, s) =>
    `${t.name} is ${t.county} County, ${s}, ${n[0].miles} miles from ${n[0].town} and ${n[1].miles} from ${n[1].town}. It is inside our ${s === 'Massachusetts' ? 'core' : 'regular'} run, not an outlying job.`,
  (t, n, s) =>
    `${t.name} is in ${t.county} County, ${s}, ${n[0].miles} miles from ${n[0].town} and ${n[1].miles} from ${n[1].town} — on the route either way.`,
]

function list(n) {
  const names = n.map((x) => x.town)
  return names.length > 2
    ? `${names.slice(0, -1).join(', ')} and ${names[names.length - 1]}`
    : names.join(' and ')
}

function main() {
  if (!fs.existsSync(IN)) {
    console.error(`no ${IN} — run admin-phaora's tmp-towngap.mts first`)
    process.exit(1)
  }
  const gap = JSON.parse(fs.readFileSync(IN, 'utf8'))

  // Only towns that will actually have a page can be linked as neighbours; a
  // nearby link to a directory that does not exist is a 404 on every page that
  // names it.
  const existing = new Set(
    fs.readdirSync(ROOT)
      .filter((d) => /^masonry-[a-z-]+-(ma|ri|nh|me|ct)$/.test(d))
      .map((d) => d.replace(/^masonry-/, '')),
  )
  const willExist = new Set([
    ...existing,
    ...gap.map((t) => `${t.slug}-${t.state}`),
  ])

  const entries = []
  const skipped = []

  gap.forEach((t, i) => {
    if (!t.county) { skipped.push(`${t.name}, ${t.state} — no county resolved`); return }

    const near = (t.nearby || [])
      .filter((n) => willExist.has(`${slugify(n.town)}-${n.state.toLowerCase()}`))
      .slice(0, 3)
    if (near.length < 2) { skipped.push(`${t.name}, ${t.state} — fewer than two linkable neighbours`); return }

    const stateName = STATE_NAME[t.state]
    if (!stateName) { skipped.push(`${t.name} — unknown state '${t.state}'`); return }

    entries.push({
      slug: t.slug,
      name: t.name,
      state: t.state,
      county: t.county,
      // Left false throughout. The flag only selects which frost-depth
      // paragraph prints, and the inland one ends 'we build to the depth your
      // building department gives, and we ask before we dig' — true in every
      // town on this list, and it claims nothing.
      coastal: false,
      workingIn: FORMS[i % FORMS.length](t, near, stateName),
      nearby: near.map((n) => `${slugify(n.town)}|${n.state.toLowerCase()}`),
    })
  })

  const body =
    `/**\n` +
    ` * Towns the bench holds that had no page.\n` +
    ` *\n` +
    ` * GENERATED by scripts/build-town-gap-data.js — do not hand-edit; edit the\n` +
    ` * generator or promote an entry into the hand-written list in\n` +
    ` * generate-town-pages.js, which this file never touches.\n` +
    ` *\n` +
    ` * County is from the Census geocoder, asked what county a real parcel in that\n` +
    ` * town falls in. Distances are measured between parcel-median centroids. No\n` +
    ` * sentence here asserts anything that did not come from one of those two.\n` +
    ` */\n` +
    `module.exports = ${JSON.stringify(entries, null, 2)};\n`

  fs.writeFileSync(OUT, body)
  console.log(`${OUT} — ${entries.length} towns`)
  for (const s of skipped) console.log(`  skipped: ${s}`)
}

main()
